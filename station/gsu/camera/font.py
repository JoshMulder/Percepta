#: char → tuple of 7 rows, each a tuple of 5 booleans. Built once at import.
GLYPHS = {
    char: tuple(
        tuple(pattern[row * WIDTH + column] == "#" for column in range(WIDTH))
        for row in range(HEIGHT)
    )
    for char, pattern in _GLYPHS.items()
}

_FALLBACK = GLYPHS["?"]


def glyph(char: str) -> tuple[tuple[bool, ...], ...]:
    return GLYPHS.get(char.upper(), _FALLBACK)


def text_width(text: str) -> int:
    """Width in font pixels, with no trailing inter-character gap."""
    return max(0, len(text) * ADVANCE - 1)


def fits(text: str, columns: int) -> str:
    """As much of `text` as will fit in `columns` font pixels."""
    if columns < WIDTH:
        return ""
    return text[: (columns + 1) // ADVANCE]
